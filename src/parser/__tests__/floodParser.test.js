describe('parseFloodLine', () => {
    it('should parse simple case without breakdown', () => {
        const line = '«Волга» (Чувашэнерго. Чувашская Республика): 2 опоры 1 ЛЭП 110 кВ (уровень вод 50 см, талые воды)';
        const result = parseFloodLine(line);

        expect(result).toEqual({
            company: '«Волга» (Чувашэнерго)',
            region: 'Чувашская Республика',
            totalPoles: 2,
            totalLines: 1,
            voltageRange: '110 кВ',
            breakdown: []
        });
    });

    it('should parse complex case with breakdown', () => {
        const line = '«Томск» (Томская область): 194 опоры, из них 174 опоры 5 ЛЭП 10 кВ, 20 опор 3 ЛЭП 0,4 кВ, 3 ТП (уровень вод 100 см, р. Томь, Обь)';
        const result = parseFloodLine(line);

        expect(result.company).toBe('«Томск»');
        expect(result.region).toBe('Томская область');
        expect(result.totalPoles).toBe(194);
        expect(result.totalLines).toBe(8); // 5 + 3
        expect(result.voltageRange).toBe('0,4-10 кВ');
        expect(result.breakdown).toHaveLength(2);
    });
});

describe('parseFloodData', () => {
    it('should parse multiple lines and group by federal district', () => {
        const result = parseFloodData(sampleInput);

        expect(result).toHaveProperty('Приволжский ФО');
        expect(result).toHaveProperty('Южный ФО');
        expect(result).toHaveProperty('Сибирский ФО');

        const privolzhsky = result['Приволжский ФО'];
        expect(privolzhsky).toHaveProperty('Самарская область');
        expect(privolzhsky).toHaveProperty('Республика Мордовия');
        expect(privolzhsky).toHaveProperty('Чувашская Республика');
        expect(privolzhsky).toHaveProperty('Нижегородская область');
    });
});